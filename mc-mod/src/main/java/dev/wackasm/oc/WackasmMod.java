package dev.wackasm.oc;

import java.io.IOException;
import java.io.InputStream;

import li.cil.oc.api.API;
import li.cil.oc.api.Items;
import net.fabricmc.api.ModInitializer;
import net.fabricmc.fabric.api.event.lifecycle.v1.ServerLifecycleEvents;
import net.fabricmc.fabric.api.itemgroup.v1.ItemGroupEvents;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.MinecraftServer;
import net.minecraft.world.item.CreativeModeTab;
import net.minecraft.world.item.DyeColor;
import net.minecraft.world.item.ItemStack;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * Registers the WebAssembly architecture with OpenComputers: Modernized,
 * along with the two items it boots from. Together they mirror Lua's Lua BIOS
 * EEPROM and OpenOS floppy:
 * <ul>
 *   <li><b>EEPROM (WebAssembly BIOS)</b>: boots {@code /init.wasm} from a
 *       filesystem (see {@code crates/wackasm-oc-bios}).</li>
 *   <li><b>wackasm shell</b> floppy: a small shell installed as {@code /init.wasm}
 *       (see {@code crates/wackasm-oc-guest}).</li>
 * </ul>
 * Their crafting recipes are data, generated by the build (see
 * {@code generateRecipes} in {@code build.gradle}); they must make the same
 * items as the registrations here.
 *
 * <p>OpenComputers sets up its API in its own main entrypoint, and Fabric
 * doesn't order main entrypoints by dependency. So registration happens as
 * soon as the API is there: in this mod's main entrypoint if OpenComputers'
 * ran first, otherwise in {@link WackasmClient} or {@link WackasmServer},
 * which Fabric runs after every mod's main entrypoint.
 *
 * <p>The native library is only loaded on the logical server.
 */
public final class WackasmMod implements ModInitializer {
    public static final String MOD_ID = "wackasm";
    /** OpenComputers' default {@code eepromSize}. */
    private static final int EEPROM_SIZE = 4096;

    static final Logger log = LoggerFactory.getLogger(MOD_ID);

    /** The running server, for the work dir and registries; null between worlds. */
    static volatile MinecraftServer server;

    private static boolean registered;

    /** OpenComputers: Modernized's creative tab. */
    private static final ResourceKey<CreativeModeTab> OC_TAB =
            ResourceKey.create(Registries.CREATIVE_MODE_TAB, ResourceLocation.fromNamespaceAndPath("opencomputers", "main"));

    /** The EEPROM {@link #registerWithOpenComputers} registered, once it has. */
    private static volatile ItemStack biosEeprom;

    @Override
    public void onInitialize() {
        WackasmConfig.load();
        registerWithOpenComputers();
        ServerLifecycleEvents.SERVER_STARTING.register(s -> {
            server = s;
            WackasmConfig.load(); // pick up edits made since the last world
            registerWithOpenComputers();
            selfTest();
        });
        ServerLifecycleEvents.SERVER_STOPPED.register(s -> server = null);

        // OpenComputers: Modernized 1.10.7's Fabric build doesn't put EEPROMs
        // from Items.registerEEPROM in its creative tab (floppies it does), so
        // add ours, unless a fixed version already has.
        ItemGroupEvents.modifyEntriesEvent(OC_TAB).register(entries -> {
            ItemStack bios = biosEeprom;
            if (bios == null) return;
            boolean present = entries.getDisplayStacks().stream()
                    .anyMatch(stack -> ItemStack.isSameItemSameComponents(stack, bios));
            if (!present) entries.accept(bios.copy());
        });
    }

    /** Registers once, as soon as OpenComputers' API is set up. */
    static synchronized void registerWithOpenComputers() {
        if (registered) return;
        if (API.items == null || API.machine == null) return; // OpenComputers hasn't initialized yet
        registered = true;

        li.cil.oc.api.Machine.add(WackasmArchitecture.class);
        log.info("Registered the WebAssembly (wackasm) architecture with OpenComputers");

        byte[] bios = resource("/assets/wackasm/bios.wasm");
        if (bios.length > EEPROM_SIZE) {
            log.warn("The wasm BIOS is {} bytes, more than a default EEPROM holds ({})", bios.length, EEPROM_SIZE);
        }
        // Writable like the Lua BIOS: the BIOS stores its boot address in the
        // EEPROM's data, and players can reflash it. Both items show in
        // OpenComputers' creative tab (the EEPROM through the event in
        // onInitialize); the recipes make them in survival.
        biosEeprom = Items.registerEEPROM("EEPROM (WebAssembly BIOS)", bios, null, false);
        // Not FileSystem.fromClass, which finds an empty disk in dev runs; see FloppyFileSystem.
        Items.registerFloppy("wackasm shell", DyeColor.LIME.getId(), FloppyFileSystem::fromResources, true, MOD_ID);
    }

    /** Loads the native library up front so a missing build fails here, not on the first boot. */
    private static void selfTest() {
        try {
            String workDir = WackasmPaths.workDir();
            WackasmNative.destroy(WackasmNative.create(workDir, "selftest", "selftest"));
            log.info("Native library loaded for {}; work dir is {}", NativeLoader.platform(), workDir);
        } catch (Throwable t) {
            log.error("wackasm native library is unavailable on {}; WebAssembly computers will not boot",
                    NativeLoader.platform(), t);
        }
    }

    private static byte[] resource(String path) {
        try (InputStream in = WackasmMod.class.getResourceAsStream(path)) {
            if (in == null) throw new IllegalStateException("missing " + path + " in the mod jar");
            return NativeLoader.readAll(in);
        } catch (IOException e) {
            throw new IllegalStateException("reading " + path, e);
        }
    }
}
